/**
 * Generates src/contracts.gen.ts from ../shared/contracts/envelope.schema.json, which is itself
 * exported from the Python contracts (python scripts/export_contracts.py). Never edit the output.
 *
 *   npm run gen:contracts            rewrite the file
 *   npm run gen:contracts -- --check fail if the committed file is stale
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../../shared/contracts/envelope.schema.json");
const outPath = resolve(here, "../src/contracts.gen.ts");

const schema = JSON.parse(readFileSync(schemaPath, "utf8")) as JSONSchema;
const banner =
  "/* eslint-disable */\n// GENERATED by scripts/gen-contracts.ts from shared/contracts/envelope.schema.json.\n// Do not edit by hand; run `npm run gen:contracts`.\n";

const ts = await compile(schema, "Message", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  format: true,
});

if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== ts) {
    console.error("contracts.gen.ts is stale: run `npm run gen:contracts`");
    process.exit(1);
  }
  console.log("contracts.gen.ts: up to date");
} else {
  writeFileSync(outPath, ts, { encoding: "utf8" });
  console.log(`wrote ${outPath}`);
}
